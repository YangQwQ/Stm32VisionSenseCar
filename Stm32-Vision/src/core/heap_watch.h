#pragma once
#include <stdint.h>

// =====================================================================
//  内部堆水位哨兵
//
//  为什么需要它：WiFi 驱动的 RX 缓冲必须落在 **DMA 可用的内部 RAM**，
//  它拿不到缓冲就一个包都收不进来 —— 表现为 WS/HTTP/ping 全哑、无 ARP 回包，
//  而 CPU/BLE 一切正常，且**再也不恢复**（复位才清）。
//
//  排查这件事时，主机上报的"堆=总空闲量"（heap=）**没有诊断价值**：
//  真正决定能否分配到缓冲的是 **DMA 可用内部最大连续块**，而这块板长期贴红线
//  （见 exec/motion_verify.cpp 里"16KB 栈从内部堆分配直接失败"的实测）。
//  所以这里 20ms 采一次，专门记这个数的最低水位，并在跌破危险线时告警。
//
//  判读：`DMA块最低` 长期在 1~2KB 徘徊 ⇒ 链路随时会哑，先腾内部 RAM 再谈别的。
//  实测：健康基线 ≈7k；AI 一轮可压到内部堆 `最低=1k`，链路随即全哑且不自愈。
//
//  读数怎么拿（两种，都走 BLE，卡死时同样可达）：
//    · `/log` 回执的体征行带 `DMA块最低=` —— 不依赖日志转发开关，最省事；
//    · `/log net on` 看 `[水位]` 行。
//  AI 任务在起点 `reset_min()`，故该值 = **最近一轮任务的最深点**（无任务时是开机至今的最深点）。
// =====================================================================

namespace hwatch {

void init();                     // 起采样任务（栈放 PSRAM，内部堆太紧）；setup 里随 blog 一起拉起
bool ready();                    // 采样任务起来了没——两个 min_* 的 0 有歧义，判读前先问这句
void reset_min();                // 开始关注一段（如 AI 一轮）之前清零水位
uint32_t min_free_internal();    // 自 reset 起：内部堆最低空闲字节（未启动=0）
uint32_t min_largest_dma();      // 自 reset 起：DMA 可用内部最大连续块最低字节（未启动=0）
uint32_t cur_largest_dma();      // **当前**：DMA 可用内部最大连续块字节（未启动=0）
uint32_t cur_free_internal();    // **当前**：内部堆空闲字节（未启动=0）
void report(const char* tag);    // 打一行最低水位（含当前值）

}  // namespace hwatch
