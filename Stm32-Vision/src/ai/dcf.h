#pragma once
// ============================ 相关滤波跟踪内核（MOSSE 思路） ============================
// 为什么换掉原来的"穷举 ZNCC"：
//   ① 速度：原实现对 5 个尺度 × 约 2600 个位置各做一次模板匹配 ≈ 230ms/帧；相关滤波把整张响应
//      图**一次 FFT 算出来**，64×64 网格一次相关约 1ms，一帧跑 3 档尺度也就几 ms。
//   ② 鲁棒：原实现是"锁定那一帧的模板 + 学一次就不再更新的判别方向"，车一转/一逼近就过期（真机实测
//      conf 从 0.92 缓慢退化到 0.55~0.62 后卡死，全图重捕同样救不回）。相关滤波**每帧在线更新**，
//      并且自带 PSR（峰值旁瓣比）作为"这次到底可不可信"的判据。
//
// 关键设计：输入窗**重采样归一化**到固定的 64×64 网格 ⇒ 目标在网格里的大小与它真实大小无关 ⇒
// **同一个滤波器对任何尺度都成立**。于是"尺度搜索"退化成"换几个源窗大小各算一次响应、取 PSR 最高的"，
// 既处理了"逼近时目标变大"，也顺带能在丢失时把源窗放大 = 扩大搜索半径。
//
// 纯灰度输入（不再需要色度/判别式）；FFT 是本文件自带的 radix-2 实现（不依赖 ESP-DSP，免踩 API 坑）。
#include <stdint.h>

namespace dcf {

// 初始化：分配 PSRAM 缓冲、预计算 Hann 窗与高斯期望响应。setup 期调一次。返回 false=内存不足。
bool init();

// 以 (u,v)（归一化）+ 目标边长 obj_norm（归一化，框的长边）起跟；*psr 回填首帧的峰值旁瓣比。
// chr = 同一帧的**饱和度平面**（max-min，可为空）。它**不参与找目标**，只在"目标本身有颜色"时
// 给响应图做一次加权：饱和度不像目标的格子被压低。见 dcf.cpp 的说明。
bool start(const uint8_t* gray, const uint8_t* chr, int gw, int gh, float u, float v, float obj_norm, float* psr);

struct Upd {
  bool  ok;       // 本帧是否拿到可信位置
  float u, v;     // 归一化位置
  float psr;      // 峰值旁瓣比（越大越可信）
  float scale;    // 本帧胜出的尺度（相对起跟时的目标大小；1.0=没变）
  // ---- 诊断用（不参与决策）----
  float obj_px;   // 本帧用的目标边长(px)；明显小于实际目标 ⇒ 窗太小、峰会在目标内部乱跳
  float off_frac; // 响应峰离窗心的距离 ÷ 搜索半径；接近/超过 1 ⇒ 目标已贴窗边（窗小 或 单步位移太大）
  // **种子外观相似度**（本帧的窗 vs 起跟那一帧的窗，零均值归一化互相关，1=一模一样）。
  // 关键：在线学习会让滤波器"跟着新看到的东西走"，锁到随车固定的夹爪时 conf/PSR 反而更高 ——
  // 只有跟**初始外观**比才能发现"已经不是那个物体了"。此值低 ⇒ 本帧**不拿去训练滤波器**。
  float appear;
};

// 用一帧灰度图更新位置。pred_u/pred_v = 预测中心（归一化，一般来自控制量先验/上一帧位移）。
// wide=true 时用更大的尺度候选（=更宽的搜索半径），供"丢失后重捕"用。
// need_psr：**本帧的最低可信度**。不达标就当作"本帧没跟上"：位置、尺度、滤波器**一律不动**
// —— 这一条是防死亡螺旋的关键（曾经只挡训练、位置/尺度照更新 ⇒ 一帧坏匹配把窗口缩小，越缩越小）。
Upd update(const uint8_t* gray, const uint8_t* chr, int gw, int gh, float pred_u, float pred_v, bool wide, float need_psr);

void stop();          // 清状态（下次要重新 start）
bool active();        // 是否处于跟踪中
// 当前搜索半径（归一化 u/v 方向）= (K_WIN-1)/2 × 目标尺寸 ÷ 图宽/高。
// 供夹取闭环**限制单步动作幅度**：一步的预期位移（`du/deg × 角度`、`dv/cm × 距离`）必须落在半径内，
// 否则目标一步就出窗——这正是"半径该由预期位移决定"的可落地做法（半径本身受归一化约束，不能独立定）。
void radius_norm(float* ru, float* rv);

// 本次跟踪是否启用了"车身 mask"（起跟点落在车身里时会自动关闭）。仅供日志/诊断。
bool mask_on();
// 本次跟踪是否启用了"色度加权门"（目标本身有颜色时才会开）。仅供日志/诊断。
bool sat_on();

// 探针：在给定位置算"与种子的外观相似度"（= seed_ncc，1=一模一样），**不动任何跟踪状态**。
// 供合爪自检比较"地面原位"和"夹持位"哪边更像目标 —— 跟踪器本身在抬臂途中常会跟丢并锁回地面，
// 所以不能只看它报的位置，得直接问这两个点。
float appear_at(const uint8_t* gray, int gw, int gh, float u, float v);

}  // namespace dcf
