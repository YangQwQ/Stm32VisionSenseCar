// 坐标系原点=车头，但四轮差速原地旋转的枢轴是车几何中心、不是车头原点——于是旋转时车头原点
// 本身会移动。car_update_pose 拿车头相对枢轴的距离折算这段位移，否则旋转后记忆坐标整体漂移
// （实测原地转 90° 车头漂到 (5,-5)~(5,-6.5)，方向=右转右后/左转左后，与刚性枢轴模型一致）。
