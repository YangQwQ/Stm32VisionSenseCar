// 固定抬臂位（arm 指令 act="raise" 的落点）：夹取后验证/看清爪下时一次到位（S 形缓动，
// 非持续 lift_up 步进，天然不会在边界抽搐）。低姿位/折叠位之外的第三个固定位，实机复核后调。
