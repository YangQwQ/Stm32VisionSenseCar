// 偏差是常态（FK∘IK 在稀疏点处不互逆），而状态行会把偏差报成"位姿没到位"、让 AI 以为动作失败。
// 现值是**实机逐点核过、落点无诊断**的一组：(8.0,1.0) → 实际落 (8,1)，pwm 170/232。
inline constexpr float ARM_LOW_X_CM = 8.0f;
