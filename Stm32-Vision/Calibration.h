// 低处很窄），于是它反解出来的 pwm 就是真值，不靠外插。用法：先把爪降到这儿，再靠车的前后移动
// 把目标送进两指之间 —— 比让上层去猜一个够不着的 (x,h) 可靠（猜错的代价是空夹且无任何报错）。
